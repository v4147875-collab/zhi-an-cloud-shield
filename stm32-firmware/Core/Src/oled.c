/* 使用的 I2C handle 名称需与 oled.h 中声明一致 */
extern I2C_HandleTypeDef OLED_I2C_HANDLE;

/* SSD1306 控制字 */
static const uint8_t SSD1306_CMD = 0x00;
static const uint8_t SSD1306_DATA = 0x40;

/* 简化的发送命令/数据封装 */
static void ssd1306_write_cmd(uint8_t cmd) {
    uint8_t buf[2] = {SSD1306_CMD, cmd};
    HAL_I2C_Master_Transmit(&OLED_I2C_HANDLE, SSD1306_I2C_ADDR, buf, 2, 100);
}

static void ssd1306_write_data(uint8_t *data, uint16_t size) {
    const uint16_t chunk = 16;
    uint16_t sent = 0;
    while (sent < size) {
        uint16_t tosend = (size - sent) > chunk ? chunk : (size - sent);
        uint8_t buf[1 + chunk];
        buf[0] = SSD1306_DATA;
        memcpy(&buf[1], data + sent, tosend);
        HAL_I2C_Master_Transmit(&OLED_I2C_HANDLE, SSD1306_I2C_ADDR, buf, 1 + tosend, 100);
        sent += tosend;
    }
}

/* 基本初始化序列（适用于常见 SSD1306 128x64） */
void OLED_Init(void) {
    HAL_Delay(100);
    ssd1306_write_cmd(0xAE); // display off
    ssd1306_write_cmd(0xD5); ssd1306_write_cmd(0x80); // clock
    ssd1306_write_cmd(0xA8); ssd1306_write_cmd(0x3F); // multiplex 1/64
    ssd1306_write_cmd(0xD3); ssd1306_write_cmd(0x00); // display offset
    ssd1306_write_cmd(0x40); // start line
    ssd1306_write_cmd(0x8D); ssd1306_write_cmd(0x14); // charge pump
    ssd1306_write_cmd(0x20); ssd1306_write_cmd(0x00); // memory mode
    ssd1306_write_cmd(0xA1); // seg remap
    ssd1306_write_cmd(0xC8); // com scan dec
    ssd1306_write_cmd(0xDA); ssd1306_write_cmd(0x12); // com pins
    ssd1306_write_cmd(0x81); ssd1306_write_cmd(0xCF); // contrast
    ssd1306_write_cmd(0xD9); ssd1306_write_cmd(0xF1); // precharge
    ssd1306_write_cmd(0xDB); ssd1306_write_cmd(0x40); // vcom detect
    ssd1306_write_cmd(0xA4); // resume RAM display
    ssd1306_write_cmd(0xA6); // normal display
    ssd1306_write_cmd(0x2E); // deactivate scroll
    ssd1306_write_cmd(0xAF); // display on
    OLED_Clear();
}

/* 128x64 buffer 按 page(8 pixel) 存 */
static uint8_t oled_buffer[128 * 8];

void OLED_Clear(void) {
    memset(oled_buffer, 0x00, sizeof(oled_buffer));
    for (uint8_t page = 0; page < 8; page++) {
        ssd1306_write_cmd(0xB0 + page);
        ssd1306_write_cmd(0x00);
        ssd1306_write_cmd(0x10);
        ssd1306_write_data(&oled_buffer[page * 128], 128);
    }
}

