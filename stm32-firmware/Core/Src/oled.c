/* 简单函数：在指定 page(y) 与列 x 显示 6x8 字符串 */
void OLED_ShowString(uint8_t x, uint8_t y, const char *str) {
    uint8_t col = x;
    uint8_t page = y;
    while (*str && col < 128) {
        char c = *str++;
        if (c < 0x20 || c > 0x7E) c = '?';
        uint8_t idx = (uint8_t)(c - 0x20);
        const uint8_t *p = F6x8[idx];
        if (page < 8) {
            memcpy(&oled_buffer[page * 128 + col], p, 6);
            col += 6;
        } else {
            break;
        }
    }
    for (uint8_t pg = page; pg <= page; pg++) {
        ssd1306_write_cmd(0xB0 + pg);
        ssd1306_write_cmd((uint8_t)(x & 0x0F));
        ssd1306_write_cmd((uint8_t)(0x10 | ((x >> 4) & 0x0F)));
        ssd1306_write_data(&oled_buffer[pg * 128], 128);
    }
}

/* 高级显示函数：显示 Init 状态 在第一行 */
void OLED_ShowInitState(OLED_InitState_t s) {
    OLED_ShowString(0, 0, "Init: ");
    if (s == OLED_INITING) {
        OLED_ShowString(48, 0, "Init...");
    } else if (s == OLED_OK) {
        OLED_ShowString(48, 0, "OK     ");
    } else {
        OLED_ShowString(48, 0, "ERROR  ");
    }
}

/* 显示 W5500 版本 在第二行 */
void OLED_ShowW5500Version(uint8_t ver) {
    char buf[16];
    snprintf(buf, sizeof(buf), "W5500:0x%02X", ver);
    OLED_ShowString(0, 1, buf);
}

/* 链接状态 在第三行 */
void OLED_ShowLinkState(OLED_LinkState_t s) {
    OLED_ShowString(0, 2, "Link: ");
    if (s == NET_LINK_UP) OLED_ShowString(48, 2, "LINK UP  ");
    else OLED_ShowString(48, 2, "LINK DOWN");
}

/* TCP 状态 在第四行 */
void OLED_ShowTCPState(OLED_TCPState_t s) {
    OLED_ShowString(0, 3, "TCP: ");
    if (s == TCP_WAITING) OLED_ShowString(48, 3, "Waiting... ");
    else OLED_ShowString(48, 3, "Connected  ");
}

/* 累计收发 在第五、六行 */
void OLED_UpdateStats(uint32_t rx_total, uint32_t tx_total) {
    char buf[20];
    snprintf(buf, sizeof(buf), "RX:%lu", (unsigned long)rx_total);
    OLED_ShowString(0, 4, buf);
    snprintf(buf, sizeof(buf), "TX:%lu", (unsigned long)tx_total);
    OLED_ShowString(0, 5, buf);
}